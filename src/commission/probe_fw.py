#!/usr/bin/env python3
"""
probe_fw.py - the commission probe image, generated from board.yml.

`mcuflow commission --probe` flashes this onto the DUT instead of the app: a
small, known-good ESP-IDF program whose only job is to report what is attached,
so a missing device is a bench finding, never an app crash. It prints one line
per finding to the console:

    MCUFLOW-PROBE {"kind":"start","fw":"mcuflow-probe-1","project":"..."}
    MCUFLOW-PROBE {"kind":"i2c_bus","bus":"i2c0","sda_idle":1,"scl_idle":1,"error":null}
    MCUFLOW-PROBE {"kind":"i2c_device","bus":"i2c0","device":"temp","addr":118,"result":"ack"}
    MCUFLOW-PROBE {"kind":"i2c_scan","bus":"i2c0","found":[118]}
    MCUFLOW-PROBE {"kind":"done"}

What it probes: every I2C device with an address on an I2C bus in pins:, by
address ACK (i2c_master_probe), plus a scan of each bus so a wrong address shows
which one did answer. What it cannot probe yet is listed with a reason by
probe_plan() and reported as unverified: plain GPIO pins, SPI and UART buses,
and gpio/adc/SPI devices - nothing on the bench observes those.

The C targets the ESP-IDF v6 driver split (esp_driver_i2c / i2c_master.h), the
same API the scaffold uses.
"""

from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path

PROBE_FW = "mcuflow-probe-1"
MARK = "MCUFLOW-PROBE "
DONE_LINE = MARK + '{"kind":"done"}'


def safe_name(s):
    """A board.yml name as it appears in C strings and the probe's JSON."""
    return re.sub(r"[^A-Za-z0-9_.-]", "_", str(s))


def _is_int(v):
    return isinstance(v, int) and not isinstance(v, bool)


def probe_plan(board):
    """{"i2c": [{bus, sda, scl, devices: [{name, part, addr}]}], "unprobed": [(key, reason)]}"""
    pins = board.get("pins") or {}
    devices = board.get("devices") or {}
    i2c = []
    unprobed = []
    for name, val in pins.items():
        if (
            name.startswith("i2c")
            and isinstance(val, dict)
            and _is_int(val.get("sda"))
            and _is_int(val.get("scl"))
        ):
            devs = [
                {"name": dname, "part": str(dev.get("part")), "addr": dev["address"]}
                for dname, dev in devices.items()
                if isinstance(dev, dict) and dev.get("bus") == name and _is_int(dev.get("address"))
            ]
            i2c.append({"bus": name, "sda": val["sda"], "scl": val["scl"], "devices": devs})
            if not devs:
                unprobed.append(("pins." + name, "an I2C bus with no device declared on it"))
        elif isinstance(val, dict):
            kind = "SPI" if name.startswith("spi") else "UART" if name.startswith("uart") else None
            unprobed.append(
                (
                    "pins." + name,
                    (kind + " buses are not probed yet") if kind else "not a bus the probe knows",
                )
            )
        else:
            unprobed.append(("pins." + name, "a plain GPIO: nothing on the bench observes it yet"))

    probed = {d["name"] for b in i2c for d in b["devices"]}
    i2c_buses = {b["bus"] for b in i2c}
    for dname, dev in devices.items():
        if dname in probed:
            continue
        bus = dev.get("bus") if isinstance(dev, dict) else None
        if isinstance(bus, str) and bus.startswith("spi"):
            reason = "an SPI device: probing it needs its own protocol (not implemented)"
        elif bus in ("gpio", "adc"):
            reason = "a " + bus + " device: nothing on the bench observes it yet"
        elif bus in i2c_buses:
            reason = "an I2C device with no address to probe"
        else:
            reason = "its bus is not an I2C bus in pins:"
        unprobed.append(("devices." + dname, reason))
    return {"i2c": i2c, "unprobed": unprobed}


_HELPERS = r"""// Generated by `mcuflow commission --probe` from board.yml - do not edit.
// A known-good probe image: it reports what is attached and nothing else, so a
// missing device is a bench finding, never an app failure. One finding per line.
#include <stdio.h>
#include <stdint.h>
#include "freertos/FreeRTOS.h"
#include "freertos/task.h"
#include "esp_err.h"
#include "driver/gpio.h"
#include "driver/i2c_master.h"

// The level a line rests at with nothing driving it and no internal pull:
// 1 means an external pull-up is present (an I2C bus needs one).
static int idle_level(int pin)
{
    gpio_reset_pin(pin);
    gpio_set_direction(pin, GPIO_MODE_INPUT);
    gpio_set_pull_mode(pin, GPIO_FLOATING);
    vTaskDelay(pdMS_TO_TICKS(5));
    return gpio_get_level(pin);
}

static void probe_i2c_bus(const char *bus, int sda, int scl,
                          const char *const *names, const uint16_t *addrs, int n)
{
    int sda_idle = idle_level(sda);
    int scl_idle = idle_level(scl);
    i2c_master_bus_config_t cfg = {
        .i2c_port = -1,  // any free controller
        .sda_io_num = sda,
        .scl_io_num = scl,
        .clk_source = I2C_CLK_SRC_DEFAULT,
        .glitch_ignore_cnt = 7,
        .flags.enable_internal_pullup = true,
    };
    i2c_master_bus_handle_t h = NULL;
    esp_err_t err = i2c_new_master_bus(&cfg, &h);
    if (err != ESP_OK) {
        printf("MCUFLOW-PROBE {\"kind\":\"i2c_bus\",\"bus\":\"%s\",\"sda_idle\":%d,"
               "\"scl_idle\":%d,\"error\":\"%s\"}\n",
               bus, sda_idle, scl_idle, esp_err_to_name(err));
        return;
    }
    printf("MCUFLOW-PROBE {\"kind\":\"i2c_bus\",\"bus\":\"%s\",\"sda_idle\":%d,"
           "\"scl_idle\":%d,\"error\":null}\n",
           bus, sda_idle, scl_idle);
    for (int i = 0; i < n; i++) {
        esp_err_t r = i2c_master_probe(h, addrs[i], 50);
        printf("MCUFLOW-PROBE {\"kind\":\"i2c_device\",\"bus\":\"%s\",\"device\":\"%s\","
               "\"addr\":%u,\"result\":\"%s\"}\n",
               bus, names[i], (unsigned)addrs[i], r == ESP_OK ? "ack" : esp_err_to_name(r));
    }
    // Scan the 7-bit range so a wrong address shows which one did answer.
    char found[512];
    int len = 0;
    found[0] = '\0';
    for (uint16_t a = 0x08; a < 0x78; a++) {
        if (i2c_master_probe(h, a, 10) == ESP_OK && len < (int)sizeof(found) - 8) {
            len += snprintf(found + len, sizeof(found) - len, "%s%u", len ? "," : "", (unsigned)a);
        }
    }
    printf("MCUFLOW-PROBE {\"kind\":\"i2c_scan\",\"bus\":\"%s\",\"found\":[%s]}\n", bus, found);
    i2c_del_master_bus(h);
}
"""


def gen_main_c(board):
    plan = probe_plan(board)
    project = safe_name((board.get("meta") or {}).get("project", "project"))
    L = [_HELPERS, "void app_main(void)", "{"]
    L.append(
        '    printf("MCUFLOW-PROBE {\\"kind\\":\\"start\\",\\"fw\\":\\"'
        + PROBE_FW
        + '\\",\\"project\\":\\"'
        + project
        + '\\"}\\n");'
    )
    for i, b in enumerate(plan["i2c"]):
        devs = b["devices"]
        bus = safe_name(b["bus"])
        L.append("    // " + bus + ": SDA=GPIO" + str(b["sda"]) + ", SCL=GPIO" + str(b["scl"]))
        if devs:
            names = ", ".join('"' + safe_name(d["name"]) + '"' for d in devs)
            addrs = ", ".join(str(d["addr"]) for d in devs)
            L.append("    {")
            L.append("        static const char *const n" + str(i) + "[] = {" + names + "};")
            L.append("        static const uint16_t a" + str(i) + "[] = {" + addrs + "};")
            L.append(
                '        probe_i2c_bus("'
                + bus
                + '", '
                + str(b["sda"])
                + ", "
                + str(b["scl"])
                + ", n"
                + str(i)
                + ", a"
                + str(i)
                + ", "
                + str(len(devs))
                + ");"
            )
            L.append("    }")
        else:
            L.append(
                '    probe_i2c_bus("'
                + bus
                + '", '
                + str(b["sda"])
                + ", "
                + str(b["scl"])
                + ", NULL, NULL, 0);"
            )
    L.append('    printf("MCUFLOW-PROBE {\\"kind\\":\\"done\\"}\\n");')
    L.append("    fflush(stdout);")
    L.append("    while (1) {")
    L.append("        vTaskDelay(pdMS_TO_TICKS(1000));")
    L.append("    }")
    L.append("}")
    return "\n".join(L) + "\n"


def gen_sdkconfig(board):
    lines = ["# Generated by mcuflow commission --probe from board.yml build.sdkconfig."]
    for k, v in ((board.get("build") or {}).get("sdkconfig") or {}).items():
        val = "y" if v is True else "n" if v is False else str(v)
        lines.append(str(k) + "=" + val)
    return "\n".join(lines) + "\n"


def write_project(board, out_dir):
    """Write the probe image's ESP-IDF project into out_dir; returns out_dir."""
    out = Path(out_dir)
    plan = probe_plan(board)
    project = safe_name((board.get("meta") or {}).get("project", "project")) + "_probe"
    reqs = ["esp_driver_gpio"] + (["esp_driver_i2c"] if plan["i2c"] else [])
    files = {
        "CMakeLists.txt": (
            "cmake_minimum_required(VERSION 3.16)\n"
            "include($ENV{IDF_PATH}/tools/cmake/project.cmake)\n"
            "project(" + project + ")\n"
        ),
        "sdkconfig.defaults": gen_sdkconfig(board),
        "main/CMakeLists.txt": (
            'idf_component_register(SRCS "main.c"\n'
            '                       INCLUDE_DIRS "."\n'
            "                       REQUIRES " + " ".join(reqs) + ")\n"
        ),
        "main/main.c": gen_main_c(board),
        "probe.json": json.dumps(
            {"fw": PROBE_FW, "fingerprint": fingerprint(board), "plan": plan}, indent=2
        )
        + "\n",
    }
    for rel, text in files.items():
        p = out / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(text.encode("utf-8"))
    return out


def fingerprint(board):
    """12 hex chars naming the probe image: what it probes, the chip, the build
    config and this generator's own source, so any change rebuilds it."""
    basis = {
        "fw": PROBE_FW,
        "chip": (board.get("meta") or {}).get("chip"),
        "plan": probe_plan(board),
        "sdkconfig": (board.get("build") or {}).get("sdkconfig") or {},
        "gen": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
    }
    blob = json.dumps(basis, sort_keys=True, default=str).encode("utf-8")
    return hashlib.sha256(blob).hexdigest()[:12]


def parse(lines):
    """The probe findings (dicts) in the order printed; boot noise is skipped."""
    dec = json.JSONDecoder()
    out = []
    for ln in lines or []:
        i = ln.find(MARK)
        if i == -1:
            continue
        try:
            obj, _ = dec.raw_decode(ln[i + len(MARK) :].strip())
        except ValueError:
            continue
        if isinstance(obj, dict):
            out.append(obj)
    return out
